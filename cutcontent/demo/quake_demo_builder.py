def box_part(low, high, skin_area):
    """24 vertices (4 per side) so every side gets the whole skin area."""
    (x0, y0, z0), (x1, y1, z1) = low, high
    sides = [
        [(x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)],
        [(x0, y1, z0), (x1, y1, z0), (x1, y0, z0), (x0, y0, z0)],
        [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)],
        [(x1, y1, z0), (x0, y1, z0), (x0, y1, z1), (x1, y1, z1)],
        [(x0, y1, z0), (x0, y0, z0), (x0, y0, z1), (x0, y1, z1)],
        [(x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)],
    ]
    s0, t0, s1, t1 = skin_area
    corners = [(s0, t1), (s1, t1), (s1, t0), (s0, t0)]
    vertices, coordinates, triangles = [], [], []
    for side in sides:
        base = len(vertices)
        vertices.extend(side)
        coordinates.extend((0, s, t) for s, t in corners)
        triangles.append((1, base, base + 1, base + 2))
        triangles.append((1, base, base + 2, base + 3))
    return vertices, coordinates, triangles


def rotate_about(point, pivot, angle, axis):
    x, y, z = (point[i] - pivot[i] for i in range(3))
    cosine, sine = math.cos(angle), math.sin(angle)
    if axis == "y":
        x, z = x * cosine + z * sine, -x * sine + z * cosine
    else:
        y, z = y * cosine - z * sine, y * sine + z * cosine
    return (x + pivot[0], y + pivot[1], z + pivot[2])


def assemble_model(parts, frames_spec, skin) -> bytes:
    """parts: name -> (low, high, skin area, pivot); frames_spec: list of (frame name, {part: (angle, axis, lift)})."""
    vertices, coordinates, triangles, owners = [], [], [], []
    for name, (low, high, area, _pivot) in parts.items():
        part_vertices, part_coordinates, part_triangles = box_part(low, high, area)
        base = len(vertices)
        vertices += part_vertices
        coordinates += part_coordinates
        triangles += [(front, a + base, b + base, c + base) for front, a, b, c in part_triangles]
        owners += [name] * len(part_vertices)
    posed_frames = []
    for frame_name, pose in frames_spec:
        positions = []
        for vertex, owner in zip(vertices, owners):
            angle, axis, lift = pose.get(owner, (0.0, "y", 0.0))
            moved = rotate_about(vertex, parts[owner][3], angle, axis) if angle else vertex
            positions.append((moved[0], moved[1], moved[2] + lift))
        posed_frames.append((frame_name, positions))
    minimum = [min(p[axis] for _, frame in posed_frames for p in frame) for axis in range(3)]
    maximum = [max(p[axis] for _, frame in posed_frames for p in frame) for axis in range(3)]
    scale = tuple(max((maximum[axis] - minimum[axis]) / 255.0, 1e-3) for axis in range(3))
    quantised = [
        (name, [tuple(int(round((p[axis] - minimum[axis]) / scale[axis])) for axis in range(3)) for p in frame])
        for name, frame in posed_frames
    ]
    return quake_model.build_model(64, 64, skin, coordinates, triangles, quantised, scale, tuple(minimum))


def paint_skin(body: int, accent: int) -> bytes:
    pixels = bytearray()
    for y in range(64):
        for x in range(64):
            area = (y // 32) * 2 + x // 32
            ramp = (body, accent, SKIN, STEEL)[area]
            detail = 2 if (x % 32 in (1, 30) or y % 32 in (1, 30)) else 0
            pixels.append(colour(ramp, 9 + noise(x, y, 7) - detail))
    return bytes(pixels)


