# ------------------------------------------------------------------ sounds
def build_wav(notes: list[tuple[float, float]], rate: int = 11025) -> bytes:
    samples = bytearray()
    for frequency, duration in notes:
        count = int(rate * duration)
        for index in range(count):
            envelope = min(1.0, index / 200) * max(0.0, 1.0 - index / count)
            value = math.sin(2 * math.pi * frequency * index / rate) * envelope if frequency else 0.0
            samples.append(int(128 + 90 * value))
    data = bytes(samples)
    header = b"RIFF" + struct.pack("<I", 36 + len(data)) + b"WAVEfmt " + struct.pack("<IHHIIHH", 16, 1, 1, rate, rate, 1, 8)
    return header + b"data" + struct.pack("<I", len(data)) + data


