"""Freely usable demo data for trying out Cut Content Anything.

- ``create_demo_game()`` writes the self-made demo game (generated by code in this
  repository, no third-party data) to ``<data directory>/demo/cut-content-demo/id1``.
- ``download_librequake()`` downloads the LibreQuake v0.09-beta "lite" release from
  its official GitHub release page, checks its SHA-256 checksum and unpacks it to
  ``<data directory>/demo/librequake-v0.09-beta``. LibreQuake's art, models and
  sounds are under the BSD 3-Clause licence; its game code (progs.dat) and
  ``gfx/pop.lmp`` are under the GNU GPL version 2. Nothing of it is stored in
  this repository.
"""

from __future__ import annotations

import hashlib
import os
import shutil
import tempfile
import urllib.request
import zipfile
from pathlib import Path

from cutcontent.core.folders import demo_folder
from cutcontent.core.settings import ensure_data_directory

LIBREQUAKE_VERSION = "v0.09-beta"
LIBREQUAKE_URL = "https://github.com/lavenderdotpet/LibreQuake/releases/download/v0.09-beta/lite.zip"
LIBREQUAKE_SHA256 = "428e736b2f01d953e09a08c60bee975bdc4a0ac2219e97fa095c8af41754da83"
LIBREQUAKE_FOLDER_NAME = "librequake-v0.09-beta"
DEMO_FOLDER_NAME = "cut-content-demo"


def create_demo_game(target: Path | None = None) -> Path:
    from cutcontent.demo.quake_demo_builder import DEMO_README, build_demo_paks

    ensure_data_directory()
    game_directory = (target or demo_folder() / DEMO_FOLDER_NAME) / "id1"
    game_directory.mkdir(parents=True, exist_ok=True)
    for name, data in build_demo_paks().items():
        (game_directory / name).write_bytes(data)
    (game_directory.parent / "README.txt").write_text(DEMO_README, encoding="utf-8")
    return game_directory


def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def download_librequake(local_zip: Path | None = None) -> Path:
    """Downloads (or takes a local copy of) the LibreQuake lite release and unpacks it."""
    ensure_data_directory()
    target = demo_folder() / LIBREQUAKE_FOLDER_NAME
    if (target / "id1" / "pak0.pak").is_file():
        return target / "id1"
    with tempfile.TemporaryDirectory() as temporary:
        archive = Path(temporary) / "lite.zip"
        if local_zip:
            shutil.copyfile(local_zip, archive)
        else:
            print(f"Downloading {LIBREQUAKE_URL} (about 56 MB)…")
            with urllib.request.urlopen(LIBREQUAKE_URL, timeout=120) as response, open(archive, "wb") as handle:
                shutil.copyfileobj(response, handle)
        checksum = file_sha256(archive)
        if checksum != LIBREQUAKE_SHA256:
            raise ValueError(f"Checksum mismatch for the LibreQuake download ({checksum}); nothing was unpacked.")
        unpack_directory = Path(temporary) / "unpacked"
        with zipfile.ZipFile(archive) as bundle:
            for member in bundle.infolist():
                destination = (unpack_directory / member.filename).resolve()
                if unpack_directory.resolve() not in destination.parents and destination != unpack_directory.resolve():
                    raise ValueError(f"Unsafe path in archive: {member.filename}")
            bundle.extractall(unpack_directory)
        source = unpack_directory / "lite"
        if target.exists():
            shutil.rmtree(target)
        shutil.move(str(source), str(target))
    (target / "SOURCE.txt").write_text(
        f"LibreQuake {LIBREQUAKE_VERSION} lite, downloaded from {LIBREQUAKE_URL}\n"
        f"SHA-256 {LIBREQUAKE_SHA256}\n"
        "Licences: art, models and sounds BSD 3-Clause (id1/docs/COPYING); progs.dat and gfx/pop.lmp GNU GPL v2 (id1/docs/misc-docs).\n",
        encoding="utf-8",
    )
    os.chmod(target, 0o755)
    return target / "id1"
