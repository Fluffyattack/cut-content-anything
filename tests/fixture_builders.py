def file_table_disc_banner() -> bytes:
    pixels = bytearray()
    for index in range(96 * 32):
        pixels += struct.pack(">H", 0x8000 | ((index % 32) << 10) | (8 << 5) | 20)
    return b"BNR1" + bytes(28) + bytes(pixels) + bytes(0x140)


def file_table_disc_files() -> tuple[dict[str, bytes], bytes]:
    executable = file_table_disc.build_disc_executable(b"\x00" * 64 + b"/data/stage1.arc\x00data/stage2.arc\x00audio/bgm.dsp\x00opening.bnr\x00")
    files = {
        "opening.bnr": file_table_disc_banner(),
        "data/stage1.arc": b"a" * 200,
        "data/stage2.arc": b"b" * 200,
        "data/old_stage.arc": b"c" * 200,
        "audio/bgm.dsp": b"d" * 200,
    }
    return files, executable


def file_table_disc_image() -> bytes:
    files, executable = file_table_disc_files()
    return file_table_disc.build_file_table_disc_image("TCCE01", "CCA File Table Disc Test", files, executable)


def encrypted_partition_header_image() -> bytes:
    image = bytearray(0x8000)
    image[0:6] = b"ECCE01"
    struct.pack_into(">I", image, 0x18, file_table_disc.ENCRYPTED_PARTITION_DISC_MAGIC)
    image[0x20:0x37] = b"CCA Encrypted Test Disc"
    return bytes(image)


def extracted_file_table_folder(folder: Path) -> Path:
    files, executable = file_table_disc_files()
    game = folder / "CCA_FILE_TABLE_EXTRACTED"
    (game / "sys").mkdir(parents=True)
    (game / file_table_disc.MAIN_EXECUTABLE_PATH).write_bytes(executable)
    (game / "sys" / "boot.bin").write_bytes(file_table_disc_image()[:0x440])
    for path, data in files.items():
        target = game / "files" / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return game


