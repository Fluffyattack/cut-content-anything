def cartridge_file_table_image() -> bytes:
    """Own cartridge bytes with nested files, an overlay, and a drawn icon.

    The logo area is empty. This is a scanner fixture, not a bootable game.
    """
    image = bytearray(0x10000)
    image[:12] = b"CCA EXAMPLE".ljust(12, b"\0")
    image[12:16] = b"TSTE"
    image[16:18] = b"00"
    struct.pack_into("<IIII", image, 0x20, 0x8000, 0x02000000, 0x02000000, 0x180)
    struct.pack_into("<IIII", image, 0x30, 0x8200, 0x03800000, 0x03800000, 0x100)
    arm9 = b"\0game_init\0Debug stage select menu\0art/picture.png\0"
    image[0x8000:0x8000 + len(arm9)] = arm9
    image[0x8200:0x8200 + 16] = b"audio processor\0"
    root_names = b"\x0areadme.txt\x83art" + struct.pack("<H", 0xF001) + b"\x85debug" + struct.pack("<H", 0xF002) + b"\0"
    art_names = b"\x0bpicture.png\0"
    debug_names = b"\x10unused_stage.txt\0"
    filename_table = struct.pack("<IHH", 24, 0, 3)
    filename_table += struct.pack("<IHH", 24 + len(root_names), 1, 0xF000)
    filename_table += struct.pack("<IHH", 24 + len(root_names) + len(art_names), 2, 0xF000)
    filename_table += root_names + art_names + debug_names
    image[0x8400:0x8400 + len(filename_table)] = filename_table
    struct.pack_into("<IIII", image, 0x40, 0x8400, len(filename_table), 0x8600, 4 * 8)
    struct.pack_into("<II", image, 0x50, 0x8700, 32)
    struct.pack_into("<I", image, 0x8700 + 24, 3)
    struct.pack_into("<I", image, 0x68, 0x8800)
    struct.pack_into("<H", image, 0x8800, 1)
    for tile in range(16):
        image[0x8820 + tile * 32:0x8820 + (tile + 1) * 32] = bytes([0x11 if tile % 2 == 0 else 0x22]) * 32
    image[0x8820] = 0x01  # one red pixel followed by a transparent pixel
    struct.pack_into("<16H", image, 0x8A20, 0, 0x001F, 0x7C00, *([0] * 13))
    for language in range(6):
        title = "Cartridge Example".encode("utf-16-le")
        start = 0x8A40 + language * 0x100
        image[start:start + len(title)] = title
    struct.pack_into("<H", image, 0x8802, cartridge_file_table.crc16(image[0x8820:0x9040]))
    payloads = (b"Self-made cartridge example.\n", tiny_png(), b"A development-only stage description.\n", b"overlay controller\0")
    for file_id, payload in enumerate(payloads):
        offset = 0x9200 + file_id * 0x100
        image[offset:offset + len(payload)] = payload
        struct.pack_into("<II", image, 0x8600 + file_id * 8, offset, offset + len(payload))
    struct.pack_into("<II", image, 0x80, len(image), 0x200)
    struct.pack_into("<H", image, 0x15E, cartridge_file_table.crc16(image[:0x15E]))
    return bytes(image)


def tiny_png(colour=(240, 166, 58)) -> bytes:
    return encode_png(4, 4, bytes(colour + (255,)) * 16)


def tiny_wav() -> bytes:
    samples = bytes(128 + (20 if index % 20 < 10 else -20) for index in range(800))
    return b"RIFF" + struct.pack("<I", 36 + len(samples)) + b"WAVEfmt " + struct.pack("<IHHIIHH", 16, 1, 1, 8000, 8000, 1, 8) + b"data" + struct.pack("<I", len(samples)) + samples


def eight_bit_cartridge_rom() -> bytes:
    rom = bytearray(b"\xff" * 32 * 1024)
    rom[0x100:0x104] = b"\x00\xc3\x50\x01"
    rom[0x104:0x134] = bytes(48)  # the logo area is left empty in this self-made image
    rom[0x134:0x13F] = b"CCA 8BITROM"
    rom[0x13F:0x143] = b"CCAE"
    rom[0x143] = 0x80
    rom[0x144:0x146] = b"01"
    rom[0x146:0x14D] = bytes([0x00, 0x00, 0x00, 0x00, 0x01, 0x33, 0x01])
    checksum = 0
    for value in rom[0x134:0x14D]:
        checksum = (checksum - value - 1) & 0xFF
    rom[0x14D] = checksum
    rom[0x150:0x2000] = bytes(0x2000 - 0x150)
    rom[0x2000:0x2020] = b"DEBUG MENU - STAGE SELECT\x00\x00\x00\x00\x00\x00\x00"
    for tile in range(16):
        rom[0x3000 + tile * 16 : 0x3000 + tile * 16 + 16] = bytes([0x3C, 0x7E] * 8)
    return bytes(rom)


def thirty_two_bit_cartridge_rom() -> bytes:
    rom = bytearray(64 * 1024)
    rom[0:4] = b"\x2e\x00\x00\xea"
    rom[0xA0:0xAC] = b"CCA32BITROM\x00"
    rom[0xAC:0xB0] = b"BCCE"
    rom[0xB0:0xB2] = b"01"
    rom[0xB2] = 0x96
    rom[0xBC] = 2
    rom[0xBD] = (-sum(rom[0xA0:0xBD]) - 0x19) & 0xFF
    rom[0x1000:0x1010] = b"SOUND TEST MODE\x00"
    rom[0x8000:] = b"\xff" * (len(rom) - 0x8000)
    return bytes(rom)


def raw_cd_image(iso: bytes) -> bytes:
    """Wraps 2048-byte sectors into raw Mode 2 Form 1 sectors (2352 bytes, no error codes)."""
    output = bytearray()
    for sector in range(len(iso) // 2048):
        minute, rest = divmod(sector + 150, 75 * 60)
        second, frame = divmod(rest, 75)
        bcd = lambda value: (value // 10) * 16 + value % 10
        header = bytes((bcd(minute), bcd(second), bcd(frame), 2))
        output += b"\x00" + b"\xff" * 10 + b"\x00" + header + bytes(8) + iso[sector * 2048 : (sector + 1) * 2048] + bytes(280)
    return bytes(output)


def cd_image_files() -> dict[str, bytes]:
    executable = disc_metadata.PLAIN_CD_EXECUTABLE_SIGNATURE + bytes(2040) + b"\\DATA\\LEVEL1.DAT;1\x00\\DATA\\LEVEL2.DAT;1\x00\\SOUND\\MUSIC.VAG;1\x00"
    return {
        "SYSTEM.CNF": b"BOOT = cdrom:\\GAME_000.01;1\r\nTCB = 4\r\n",
        "GAME_000.01": executable,
        "DATA/LEVEL1.DAT": b"level one" * 100,
        "DATA/LEVEL2.DAT": b"level two" * 100,
        "DATA/UNUSED_BOSS.DAT": b"boss" * 100,
        "SOUND/MUSIC.VAG": b"audio" + bytes(60),
    }


def raw_cd_image_with_cue(folder: Path) -> Path:
    iso = iso9660.build_iso(cd_image_files(), "CCA_CD", "CCA")
    (folder / "game.bin").write_bytes(raw_cd_image(iso))
    cue = folder / "game.cue"
    cue.write_text('FILE "game.bin" BINARY\n  TRACK 01 MODE2/2352\n    INDEX 01 00:00:00\n', encoding="utf-8")
    return cue


